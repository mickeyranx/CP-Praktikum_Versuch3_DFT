import matplotlib.pyplot as plt
import pandas as pd 
import numpy as np



def make_plot(filename, columns, x_max, L, colors):
    x_ticks = np.arange(0,300.0, 1.0)
    x_start = 9

    fig, ax = plt.subplots()
    x_range = np.arange(0, x_max, step = 1)
    ax.axvline(x = 9, color = "purple", label="wall")
    
    
    ax.set_xlabel("lattice point s")
    ax.set_ylabel(r'density $\rho$')
   
    
    for i,col in enumerate(columns):
        #read file
        df = pd.read_table(filename,skiprows=0)
        density = df.iloc[:,col]
        #plot
        ax.plot(x_range[x_start:x_max], density[x_start:x_max], label = r'$\eta_0 = $' + str((col+1)/10), color = colors[i])
        ax.axhline(y = ((col+1)/10)/L, linestyle = "--",  color = colors[i], label = r'$\rho_0 = $' + "{:.3f}".format(((col+1)/10)/L))
    plt.xticks(x_ticks)    
    ax.set_xlim(x_start-0.1, x_max - 1)
    plt.title("density profile at the left wall for L = " + str(L))
    plt.legend()
    plt.grid()
    plt.show()
    


